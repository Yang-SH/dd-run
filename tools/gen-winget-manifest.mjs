#!/usr/bin/env node
// O15（altrun-对照优化方案-2026-11-21.md §5.1）：winget-pkgs manifest 生成器。
//
// 从 GitHub Release 资产生成三份 yaml（version / installer / defaultLocale），
// 供向 microsoft/winget-pkgs 提交 manifest PR（提交流程本身为运维腿——维护者
// fork + PR；本脚本只负责"产物确定、字节可复现"）。
//
// 用法：
//   node tools/gen-winget-manifest.mjs --version 0.3.0 \
//     --sums dist/SHA256SUMS.txt [--out-dir dist/winget] \
//     [--repo Yang-SH/dd-run] [--asset dd-run-0.3.0-portable.zip] [--manifest-version 1.6.0]
//
// - `--sums` 指向 release.yml 产出的 SHA256SUMS.txt（全资产覆盖，sha256sum -c
//   可验）；脚本按 `--asset`（默认 `dd-run-<version>-portable.zip`）行取 SHA256，
//   避免手工复制粘贴出错。
// - 不给 `--sums` 时可用 `--sha256 <64hex>` 直传。
// - 包形态：InstallerType zip + NestedInstallerType portable（NestedInstallerFiles
//   指向 `dd-run-<version>.exe`）——解包后版本化 exe 与 `extensions.d/` 同目录，
//   宿主 exe 邻接扫描既支持（批次 7.5），zip 解包即满足「unzip & run」语义。
//
// 校验：URL 必须 https；SHA256 64 位十六进制；版本剥离前导 `v` 后须为
// MAJOR.MINOR.PATCH 三段。产物写入 `--out-dir`（默认 `dist/winget`）。
// 零第三方依赖（与 tools/docscan.mjs 同为纯 Node 标准库脚本）。

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";

// ── 参数解析 ────────────────────────────────────────────────────────────────

function parseArgs(argv) {
  const out = {};
  for (let i = 2; i < argv.length; i += 1) {
    const a = argv[i];
    const m = /^--([a-z0-9-]+)$/.exec(a);
    if (!m) {
      fail(`无法识别的参数：${a}`);
    }
    const key = m[1];
    if (key === "help") {
      usage();
      process.exit(0);
    }
    const next = argv[i + 1];
    if (next === undefined || next.startsWith("--")) {
      fail(`--${key} 缺少取值`);
    }
    out[key] = next;
    i += 1;
  }
  return out;
}

function usage() {
  console.log(`用法：node tools/gen-winget-manifest.mjs --version <ver> (--sums <SHA256SUMS.txt> | --sha256 <64hex>)
  [--out-dir dist/winget] [--repo Yang-SH/dd-run] [--asset dd-run-<ver>-portable.zip] [--manifest-version 1.6.0]`);
}

function fail(msg) {
  console.error(`[gen-winget-manifest] ${msg}`);
  process.exit(1);
}

const args = parseArgs(process.argv);

// ── 输入校验（全部显式 fail-fast，不静默兜底）─────────────────────────────

const version = String(args.version ?? "").replace(/^v/, "");
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  fail(`版本须为 MAJOR.MINOR.PATCH（前导 v 可带）：实得 ${args.version ?? "(缺)"}`);
}

const repo = args.repo ?? "Yang-SH/dd-run";
if (!/^[\w.-]+\/[\w.-]+$/.test(repo)) {
  fail(`--repo 形态应为 owner/repo：实得 ${repo}`);
}

const asset = args.asset ?? `dd-run-${version}-portable.zip`;
const installerUrl = `https://github.com/${repo}/releases/download/v${version}/${encodeURIComponent(asset)}`;
if (!installerUrl.startsWith("https://")) {
  fail("InstallerUrl 必须 https");
}

const manifestVersion = args["manifest-version"] ?? "1.6.0";
if (!/^\d+\.\d+\.\d+$/.test(manifestVersion)) {
  fail(`--manifest-version 须为三段数值：实得 ${manifestVersion}`);
}

let sha256 = args.sha256 ?? "";
if (args.sums) {
  if (!existsSync(args.sums)) {
    fail(`--sums 文件不存在：${args.sums}`);
  }
  const lines = readFileSync(args.sums, "utf8").split(/\r?\n/).filter(Boolean);
  // SHA256SUMS.txt 行形态 = `<64hex>  <文件名>`（sha256sum -c 可验口径）
  const hit = lines.find((l) => l.trimEnd().endsWith(asset));
  if (!hit) {
    fail(`SHA256SUMS.txt 中找不到 ${asset} 的行（共 ${lines.length} 行）`);
  }
  sha256 = hit.trim().split(/\s+/)[0];
}
if (!/^[0-9a-f]{64}$/.test(sha256.toLowerCase())) {
  fail(`SHA256 须为 64 位十六进制：实得 ${sha256 || "(缺)"}（给 --sums 或 --sha256）`);
}

// ── 产物（确定性字节：同输入同输出，PR diff 稳定）────────────────────────

const packageId = `${repo.replace("/", ".")}`;
const outDir = args["out-dir"] ?? join("dist", "winget");

const versionYaml = `# generated by tools/gen-winget-manifest.mjs — do not edit by hand
PackageIdentifier: ${packageId}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${manifestVersion}
`;

const installerYaml = `# generated by tools/gen-winget-manifest.mjs — do not edit by hand
PackageIdentifier: ${packageId}
PackageVersion: ${version}
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: dd-run-${version}.exe
    PortableCommandAlias: dd-run
Installers:
  - Architecture: x64
    InstallerUrl: ${installerUrl}
    InstallerSha256: ${sha256.toLowerCase()}
ManifestType: installer
ManifestVersion: ${manifestVersion}
`;

const localeYaml = `# generated by tools/gen-winget-manifest.mjs — do not edit by hand
PackageIdentifier: ${packageId}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: ${repo.split("/")[0]}
PackageName: dd-run
License: MIT
ShortDescription: A keyboard-first command palette / launcher in Rust, extensible via NDJSON JSON-RPC extensions.
Tags:
  - launcher
  - command-palette
  - rust
  - keyboard
ReleaseNotesUrl: ${installerUrl.split("/releases/download/")[0]}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: ${manifestVersion}
`;

mkdirSync(outDir, { recursive: true });
const files = [
  [`${packageId}.yaml`, versionYaml],
  [`${packageId}.installer.yaml`, installerYaml],
  [`${packageId}.en-US.yaml`, localeYaml],
];
for (const [name, body] of files) {
  writeFileSync(join(outDir, name), body, "utf8");
}

console.log(`[gen-winget-manifest] 已生成 3 份 manifest → ${outDir}/`);
for (const [name] of files) {
  console.log(`  ${name}`);
}
console.log(
  `[gen-winget-manifest] 后续（运维腿）：fork microsoft/winget-pkgs → 按版本目录提交三份 yaml → PR；\n` +
    `  提交前可用 winget 自带校验（如已装 winget source 工具）或人工比对既有包形态。`,
);
